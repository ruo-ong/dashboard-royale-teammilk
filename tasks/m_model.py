"""Workstream M - the forecast model, exactly as frozen in docs/MODEL_PROTOCOL.md (M1).

Run:  python -m tasks.m_model
  M2/M3 m3_selection        April validation MAE of every candidate; the chosen model
  M4    forecast_results    May-June, day x model: actual, forecast, error (test set used once)
        m4_metrics          MAE / MAPE / bias per model, and MAE by weekday
  M5    m5_july_forecast    refit on Jan-Jun, forecast July 1-30
        m5_decision         which July weekend to promote, and the dollars at stake
  M7    docs/MODEL.md       the write-up for the dashboard's Model page (regenerated by this script)
This task does not take --start/--end: the split is fixed by the protocol, and the dashboard says so.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from royale.data import load
from royale.outputs import read_output, write_output
from royale.paths import ROOT

FIT = ("2025-01-01", "2025-03-31")
VALIDATE = ("2025-04-01", "2025-04-30")
TRAIN = ("2025-01-01", "2025-04-30")
TEST = ("2025-05-01", "2025-06-30")
AS_OF = pd.Timestamp("2025-04-30")
JULY = pd.date_range("2025-07-01", "2025-07-30")
JULY_HOLIDAYS = {pd.Timestamp("2025-07-04"): "Independence Day"}
CLOSURE = (pd.Timestamp("2025-03-03"), pd.Timestamp("2025-04-06"))
PROMO_LEAD_DAYS = 14          # action_catalog A-PROMO
WEEKDAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]


def history() -> pd.DataFrame:
    d = load("property_day", columns=["gaming_date", "coin_in_usd", "theo_usd"])
    cal = load("calendar_day", columns=["gaming_date", "federal_holiday"])
    return d.merge(cal, on="gaming_date").rename(columns={"coin_in_usd": "y"})


def features(dates: pd.Series, holidays: pd.Series, as_of: pd.Timestamp) -> pd.DataFrame:
    """Only information known on `as_of`: weekday, holidays, events announced by then, closure, trend."""
    ev = load("events")
    ev = ev[pd.to_datetime(ev["announced_date"]) <= as_of]
    city = {d for e in ev[ev["local_scope"] == "citywide"].itertuples() for d in pd.date_range(e.start_date, e.end_date)}
    prop = {d for e in ev[ev["local_scope"] == "property"].itertuples() for d in pd.date_range(e.start_date, e.end_date)}
    dates = pd.to_datetime(pd.Series(dates).reset_index(drop=True))
    X = pd.DataFrame({"const": 1.0}, index=dates.index)
    for wd in WEEKDAYS[1:]:
        X[wd] = (dates.dt.day_name() == wd).astype(float)
    X["holiday"] = pd.Series(holidays).reset_index(drop=True).notna().astype(float)
    X["citywide_event"] = dates.isin(city).astype(float)
    X["property_promotion"] = dates.isin(prop).astype(float)
    X["closure"] = dates.between(*CLOSURE).astype(float)
    X["trend"] = (dates - pd.Timestamp("2025-01-01")).dt.days.astype(float)
    return X


class Model:
    """fit(df) / predict(dates, holidays) with df columns gaming_date, y, federal_holiday."""
    name = ""

    def __init__(self, as_of: pd.Timestamp):
        self.as_of = as_of


class ConstantMean(Model):
    name = "Baseline A: training mean"

    def fit(self, df):
        self.mean = df["y"].mean()
        return self

    def predict(self, dates, holidays):
        return np.full(len(dates), self.mean)


class WeekdayMean(Model):
    name = "Baseline B: weekday mean"

    def fit(self, df):
        self.by_wd = df.groupby(df["gaming_date"].dt.day_name())["y"].mean()
        return self

    def predict(self, dates, holidays):
        return pd.to_datetime(pd.Series(dates)).dt.day_name().map(self.by_wd).to_numpy()


class WeekdayTrend(Model):
    name = "Candidate 1: weekday mean x trend"

    def fit(self, df):
        self.wd = WeekdayMean(self.as_of).fit(df)
        ratio = df["y"].to_numpy() / self.wd.predict(df["gaming_date"], None)
        t = (df["gaming_date"] - pd.Timestamp("2025-01-01")).dt.days.to_numpy(float)
        self.coef = np.polyfit(t, ratio, 1)
        return self

    def predict(self, dates, holidays):
        t = (pd.to_datetime(pd.Series(dates)) - pd.Timestamp("2025-01-01")).dt.days.to_numpy(float)
        return self.wd.predict(dates, None) * np.polyval(self.coef, t)


class Regression(Model):
    name = "Candidate 2: regression (weekday, holiday, events, closure, trend)"

    def fit(self, df):
        X = features(df["gaming_date"], df["federal_holiday"], self.as_of)
        self.cols = [c for c in X.columns if X[c].std() > 0 or c == "const"]  # drop indicators never seen in training
        beta, *_ = np.linalg.lstsq(X[self.cols].to_numpy(), np.log(df["y"].to_numpy()), rcond=None)
        self.beta = beta
        resid = np.log(df["y"].to_numpy()) - X[self.cols].to_numpy() @ beta
        self.smear = np.mean(np.exp(resid))  # Duan smearing: unbiased back-transform from logs
        return self

    def predict(self, dates, holidays):
        X = features(dates, holidays, self.as_of)
        return np.exp(X[self.cols].to_numpy() @ self.beta) * self.smear

    def coefficients(self) -> pd.Series:
        return pd.Series(self.beta, index=self.cols)


CANDIDATES = [ConstantMean, WeekdayMean, WeekdayTrend, Regression]


def _cut(df, span):
    return df[df["gaming_date"].between(*map(pd.Timestamp, span))].reset_index(drop=True)


def metrics(actual, forecast) -> dict:
    err = forecast - actual
    return {"mae_usd": np.mean(np.abs(err)), "mape": np.mean(np.abs(err) / actual), "bias_usd": np.mean(err)}


def select(h: pd.DataFrame) -> tuple[pd.DataFrame, type]:
    fit, val = _cut(h, FIT), _cut(h, VALIDATE)
    rows = []
    for cls in CANDIDATES:
        m = cls(AS_OF).fit(fit)
        rows.append({"model": cls.name, **metrics(val["y"].to_numpy(), m.predict(val["gaming_date"], val["federal_holiday"]))})
    sel = pd.DataFrame(rows)
    b = sel.loc[sel["model"] == WeekdayMean.name, "mae_usd"].iloc[0]
    cands = sel[sel["model"].str.startswith("Candidate")].sort_values("mae_usd")
    best = cands.iloc[0]
    chosen = WeekdayMean
    if best["mae_usd"] < b:
        other = cands.iloc[1] if len(cands) > 1 else None
        chosen = next(c for c in CANDIDATES if c.name == best["model"])
        if other is not None and other["mae_usd"] <= best["mae_usd"] * 1.01 and other["model"].startswith("Candidate 1"):
            chosen = WeekdayTrend  # tie within 1% -> the simpler model
    sel["chosen"] = sel["model"] == chosen.name
    return sel, chosen


def evaluate(h: pd.DataFrame, chosen: type) -> tuple[pd.DataFrame, pd.DataFrame, Regression | None]:
    train, test = _cut(h, TRAIN), _cut(h, TEST)
    evd = load("events")
    days = {d: e.name for e in evd.itertuples() for d in pd.date_range(e.start_date, e.end_date)}
    frames, fitted = [], {}
    # The chosen model and both baselines are the evaluation. The unchosen candidates are shown for transparency
    # only; they were ruled out in April and the test result cannot change that choice.
    for cls in CANDIDATES:
        m = cls(AS_OF).fit(train)
        fitted[cls] = m
        f = test[["gaming_date", "y", "federal_holiday"]].copy()
        label = f"{cls.name} [chosen]" if cls is chosen else cls.name
        if cls not in (chosen, ConstantMean, WeekdayMean):
            label += " (not chosen in April; for transparency)"
        f["model"] = label
        f["forecast"] = m.predict(test["gaming_date"], test["federal_holiday"])
        frames.append(f)
    res = pd.concat(frames, ignore_index=True).rename(columns={"y": "actual"})
    res["error"] = res["forecast"] - res["actual"]
    res["abs_error"] = res["error"].abs()
    res["weekday"] = res["gaming_date"].dt.day_name()
    res["event"] = res["gaming_date"].map(days)
    rows = []
    for model, g in res.groupby("model", sort=False):
        rows.append({"model": model, "scope": "all test days", **metrics(g["actual"].to_numpy(), g["forecast"].to_numpy())})
        for wd in WEEKDAYS:
            s = g[g["weekday"] == wd]
            rows.append({"model": model, "scope": wd, **metrics(s["actual"].to_numpy(), s["forecast"].to_numpy())})
    return res, pd.DataFrame(rows), fitted.get(chosen)


def july(h: pd.DataFrame, chosen: type) -> tuple[pd.DataFrame, pd.DataFrame]:
    m = chosen(pd.Timestamp("2025-06-30")).fit(h)
    hol = pd.Series([JULY_HOLIDAYS.get(d) for d in JULY])
    f = pd.DataFrame({"gaming_date": JULY, "weekday": JULY.day_name(), "holiday": hol,
                      "forecast_coin_in_usd": m.predict(pd.Series(JULY), hol)})
    hold = h["theo_usd"].sum() / h["y"].sum()
    f["forecast_theo_usd"] = f["forecast_coin_in_usd"] * hold

    # Promotion weekends: Fri-Sun fully inside July and at least PROMO_LEAD_DAYS after July 1.
    events = read_output("b2_event_uplift")
    promo = events[events["local_scope"] == "property"]
    uplift_low = (promo["uplift_low_usd"] / promo["baseline_coin_in_usd"]).min()
    uplift_mid = promo["uplift_pct"].mean()
    uplift_high = (promo["uplift_high_usd"] / promo["baseline_coin_in_usd"]).max()
    rows = []
    for fri in f.loc[f["weekday"] == "Friday", "gaming_date"]:
        wk = f[f["gaming_date"].between(fri, fri + pd.Timedelta(days=2))]
        if len(wk) < 3:
            continue
        eligible = (fri - pd.Timestamp("2025-07-01")).days >= PROMO_LEAD_DAYS
        base_theo = wk["forecast_theo_usd"].sum()
        rows.append({"weekend": f"{fri:%b %-d}-{fri + pd.Timedelta(days=2):%-d}", "friday": fri, "eligible_after_lead": eligible,
                     "forecast_coin_in_usd": wk["forecast_coin_in_usd"].sum(), "forecast_theo_usd": base_theo,
                     "promo_theo_uplift_low_usd": base_theo * uplift_low, "promo_theo_uplift_usd": base_theo * uplift_mid,
                     "promo_theo_uplift_high_usd": base_theo * uplift_high})
    return f, pd.DataFrame(rows)


def weekend_check(res: pd.DataFrame) -> dict:
    """Fri-Sun totals in May-June, ordinary weekends only (no event day): how far off was each forecast?"""
    out = {}
    for label, cond in [("chosen", res["model"].str.contains(r"\[chosen\]")), ("flat", res["model"].str.startswith("Baseline A"))]:
        r = res[cond].copy()
        r = r[r["gaming_date"].dt.day_of_week >= 4]
        r["weekend"] = r["gaming_date"] - pd.to_timedelta(r["gaming_date"].dt.day_of_week - 4, unit="D")
        g = r.groupby("weekend").agg(actual=("actual", "sum"), forecast=("forecast", "sum"), days=("actual", "size"),
                                     event_days=("event", lambda e: e.notna().sum()))
        g = g[(g["days"] == 3) & (g["event_days"] == 0)]
        out[label] = (g["actual"] / g["forecast"] - 1)
    return {"weekends": len(out["chosen"]), "error_mean": out["chosen"].mean(), "error_sd": out["chosen"].std(ddof=1),
            "flat_false_lift": out["flat"].mean()}


def write_markdown(sel, met, chosen_model, decision, reg) -> None:
    allm = met[met["scope"] == "all test days"]
    lines = ["# Forecast model: protocol, validation and decision (task M7)", "",
             "Generated by `python -m tasks.m_model`. The protocol was committed before any model code: see "
             "[MODEL_PROTOCOL.md](MODEL_PROTOCOL.md).", "",
             "## 1. Model selection on April (fit Jan-Mar)", "", "| Model | April MAE | MAPE | Bias | Chosen |", "| --- | ---: | ---: | ---: | :---: |"]
    lines += [f"| {r.model} | ${r.mae_usd:,.0f} | {r.mape:.1%} | ${r.bias_usd:+,.0f} | {'yes' if r.chosen else ''} |" for r in sel.itertuples()]
    lines += ["", "## 2. One evaluation on May-June (fit Jan-Apr, forecasts frozen as of April 30)", "",
              "| Model | MAE | MAPE | Bias |", "| --- | ---: | ---: | ---: |"]
    lines += [f"| {r.model} | ${r.mae_usd:,.0f} | {r.mape:.1%} | ${r.bias_usd:+,.0f} |" for r in allm.itertuples()]
    if reg is not None:
        coef = reg.coefficients()
        lines += ["", "Regression effects (multiplicative, from Jan-Apr): " + ", ".join(
            f"{k} {np.exp(v) - 1:+.1%}" for k, v in coef.items() if k not in ("const", "trend") and k not in WEEKDAYS[1:])
                  + f"; trend {np.exp(coef.get('trend', 0) * 30) - 1:+.1%} per 30 days."]
    lines += ["", "## 3. The decision", "", decision, ""]
    (ROOT / "docs" / "MODEL.md").write_text("\n".join(lines))


def main() -> None:
    h = history()
    sel, chosen = select(h)
    write_output("m3_selection", sel)
    res, met, fitted = evaluate(h, chosen)
    write_output("forecast_results", res)
    write_output("m4_metrics", met)
    f, weekends = july(h, chosen)
    write_output("m5_july_forecast", f)

    eligible = weekends[weekends["eligible_after_lead"]].sort_values("friday")
    best, comparison = eligible.iloc[0], (eligible.iloc[1] if len(eligible) > 1 else None)
    wk = weekend_check(res)
    low, high = wk["error_mean"] - 2 * wk["error_sd"], wk["error_mean"] + 2 * wk["error_sd"]
    decision = (
        f"The chosen model (day-of-week average) forecasts a July weekend at ${best['forecast_coin_in_usd'] / 1e6:.2f}M wagered "
        f"(${best['forecast_theo_usd'] / 1000:,.0f}k expected win). We fund one promotion weekend, {best['weekend']}"
        + (f", and keep {comparison['weekend']} without a promotion as a same-month comparison" if comparison is not None else "")
        + f". At the uplift our own promotions achieved, it should add about ${best['promo_theo_uplift_usd'] / 1000:,.0f}k of expected win "
        f"(${best['promo_theo_uplift_low_usd'] / 1000:,.0f}k-${best['promo_theo_uplift_high_usd'] / 1000:,.0f}k) for $15k. "
        f"Can a lift be detected? On the {wk['weekends']} ordinary weekends of May-June, the model's weekend forecasts were off by "
        f"{wk['error_mean']:+.1%} on average (normal range {low:+.0%} to {high:+.0%}), so a lift like our tournament's (+18%) would stand out, "
        f"but one like Locals Week's (+6%) could not be told apart from forecast error. The model also changes how success is judged: "
        f"against a flat daily average, an ordinary weekend already looks {wk['flat_false_lift']:+.0%} better, so the simple baseline "
        f"would declare almost any promotion a success. The day-of-week forecast is the fair yardstick.")
    weekends["chosen"] = weekends["weekend"] == best["weekend"]
    weekends["comparison"] = weekends["weekend"] == (comparison["weekend"] if comparison is not None else "")
    write_output("m5_decision", weekends.assign(decision=decision, weekend_error_mean=wk["error_mean"], weekend_error_sd=wk["error_sd"],
                                                 flat_baseline_false_lift=wk["flat_false_lift"], ordinary_test_weekends=wk["weekends"]))
    write_markdown(sel, met, chosen, decision, fitted if isinstance(fitted, Regression) else None)

    print("M3 April validation:\n" + sel.to_string(index=False, float_format=lambda v: f"{v:,.3f}"))
    print("\nM4 May-June test:\n" + met[met["scope"] == "all test days"].to_string(index=False, float_format=lambda v: f"{v:,.3f}"))
    print("\nM5 July weekends:\n" + weekends.drop(columns=["friday", "decision"], errors="ignore").to_string(index=False, float_format=lambda v: f"{v:,.0f}"))
    print("\n" + decision)
    print("Wrote m3_selection, forecast_results, m4_metrics, m5_july_forecast, m5_decision and docs/MODEL.md")


if __name__ == "__main__":
    main()
